# ----------------------------------------------------------------- attributions
def t_attributions():
    """Which sensor each robotics attack attributes to, against the documented requirement."""
    faults = ["LedsControl", "JointControl", "WheelsControl"]
    lines = ["\\begin{table}[htbp]", "\\centering", "\\small"]
    lines += caption(
        "Top-ranked attributed variable for each robotics attack class, across all nine "
        "robotics configurations. The documented explainability requirement for this dataset "
        "is that LED attacks attribute to a tablet sensor.",
        "tab:attributions")
    lines += ["\\begin{tabular}{lllll}", "\\toprule",
              "Algorithm & Variant & LedsControl & JointControl & WheelsControl" + NL,
              "\\midrule"]
    for ai, (algo, alabel) in enumerate(ALGOS):
        rows = read(folder(algo, "robotic") + "/outputs/explainability_top_features.csv")
        by = {}
        for r in rows:
            f_ = (r.get("Fault Name") or "").replace(".csv", "")
            v_ = (r.get("Model Variant") or "").strip()
            by.setdefault(v_, {})[f_] = (r.get("Top Variable 1") or "").strip()
        # The supervisor asked that the best configuration of each algorithm be marked,
        # since that is the row whose attribution carries the most weight. Best is by
        # AUC-ROC on this domain, read from the same metrics file Table 6.1 is built from.
        auc = {}
        for r in read(folder(algo, "robotic") + "/outputs/metrics_summary.csv"):
            try:
                auc[(r.get("Model Variant") or "").strip()] = float(r["AUC_ROC"])
            except (KeyError, TypeError, ValueError):
                pass
        top = max(auc, key=auc.get) if auc else None
        for vi, v in enumerate(VARIANTS):
            if v not in by:
                continue
            acell = (MULTIROW + alabel + "}") if vi == 0 else ""
            cells = [esc(by[v].get(f, "--")) for f in faults]
            vcell = VSHORT[v]
            if v == top:
                vcell = BF + vcell + "}"
                cells = [BF + c + "}" for c in cells]
            lines.append(acell + " & " + vcell + " & " + " & ".join(cells) + NL)
