"""
Generate every LaTeX table in the thesis directly from the pipelines' own CSV outputs.

No figure in this thesis is typed by hand. Each table below is written from the CSV that
the corresponding pipeline produced, so a rerun that changes a result changes the thesis
on the next invocation of this script, not leaving a stale number behind.

This is the same guarantee tools/verify_docs.py enforces for the README, extended to the
dissertation itself. Section 2.1 of the University of Verona thesis regulation scores
"accuratezza dello svolgimento e della scrittura"; a transcription error in a results
table is the most avoidable way to lose that point.

Usage:  python Thesis/tools/make_tables.py
"""

import re
import csv
import io
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
OUT = os.path.join(ROOT, "Thesis", "tables")

DOMAINS = [("robotic", "Robotics (Pepper)"), ("healthcare", "Healthcare (PTB-XL)"),
           ("industrial", "Industrial (TEP)")]
ALGOS = [("PCMCI", "PCMCI"), ("GES", "GES"), ("CAM-UV", "CAM-UV")]
VARIANTS = ["Linear / Ridge", "Polynomial degree 3", "RBF + Ridge"]
VSHORT = {"Linear / Ridge": "Linear", "Polynomial degree 3": "Poly-3", "RBF + Ridge": "RBF"}

def bold_best(rows, cols, lower=()):
    """Bold the best value in each named column, across one block of rows.

    rows is a list of cell-lists, all the same width; cols is the indices to treat
    as performance metrics. Non-numeric cells ("--") are skipped. Ties are all
    bolded, which is the honest rendering -- suppressing one would imply a winner
    the numbers do not give.

    Columns listed in lower are the ones where small is good -- false positives,
    false negatives, seconds. Bolding the maximum there would mark the worst cell
    in the table as the best one, so the direction has to be carried per column
    and not assumed.
    """
    for c in cols:
        vals = []
        for r in rows:
            try:
                vals.append(float(r[c]))
            except (ValueError, IndexError):
                vals.append(None)
        live = [v for v in vals if v is not None]
        if not live:
            continue
        top = min(live) if c in lower else max(live)
        for r, v in zip(rows, vals):
            if v is not None and v == top:
                r[c] = BF + r[c] + "}"
    return rows


def fault_label(name):
    """Render a fault identifier as prose, not as the filename it came from.

    The CSVs carry "Attack_1" and "Fault_17" because that is what the directories
    are called. Escaped through esc() they reach the page as Attack\_1, which sets
    a visible underscore in a body-text column and reads as a variable name rather
    than as the name of a fault. The robotics classes (WheelsControl and the rest)
    carry no underscore and pass through untouched.
    """
    return str(name).replace("_", " ")


MULTIROW = "\\multirow{3}{*}{"
BF = "\\textbf{"
BFM = "\\mathbf{"   # bold inside math mode; \textbf does not bold mathematical output
NL = " \\\\"


def folder(algo, dom):
    """Map an (algorithm, domain) pair to its results directory."""
    if algo == "PCMCI":
        return "PCMCI/PCMCI_" + dom
    if algo == "GES":
        return "GES/GES_" + dom
    return "CAM-UV/CAM_UV_" + ("robotics" if dom == "robotic" else dom)


def read(path):
    p = os.path.join(ROOT, path)
    if not os.path.exists(p):
        return []
    return list(csv.DictReader(io.open(p, encoding="utf-8")))


def esc(s):
    """Escape the LaTeX specials that appear in sensor names."""
    return str(s).replace("_", "\\_").replace("&", "\\&").replace("%", "\\%")


def write(name, lines):
    path = os.path.join(OUT, name)
    header = ("% GENERATED by Thesis/tools/make_tables.py -- do not edit by hand.\n"
              "% Every figure below is read from a CSV written by the pipelines.\n")
    with io.open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(header + "\n".join(lines) + "\n")
    print("  " + name)


def cap_open(text):
    """The opening of a caption, carrying a short form when the text needs one.

    Every table goes through this, floats and longtables alike: a longtable sets its
    caption and label on one line and so cannot use caption() below, and writing the
    short form into the generated file instead loses it on the next run."""
    short = _first_sentence(text)
    return "\\caption[" + short + "]{" if short else "\\caption{"


def caption(text, label):
    """A caption explains why a table should not be misread, which belongs under
    the table and not in the list of tables. Without a short form the whole
    paragraph prints in both, so the list gets the first sentence."""
    return [cap_open(text) + text + "}", "\\label{" + label + "}"]


def _first_sentence(text):
    t = " ".join(text.split())
    if len(t) < 120:
        return None
    for m in re.finditer(r"(?<![0-9])[.] ", t):
        cand = t[:m.start()]
        if not _balanced(cand):
            continue
        if 15 < len(cand) <= 150:
            return cand
        return _clause(cand)
    return None


def _clause(sentence):
    """A first sentence too long for the list of tables, cut back to its last clause
    boundary. The opening clause names the table; what follows it qualifies."""
    cut = None
    for m in re.finditer(r", ", sentence):
        if 15 < m.start() <= 150 and _balanced(sentence[:m.start()]):
            cut = m.start()
    return sentence[:cut] if cut else None


def _balanced(s):
    return s.count("{") == s.count("}")


def sci(v):
    """Render a CSV value, promoting exponent notation to proper LaTeX mathematics."""
    s = str(v).strip()
    if "e" in s.lower():
        mant, exp = s.lower().split("e")
        return "$" + mant + " \\times 10^{" + str(int(exp)) + "}$"
    return s


# ----------------------------------------------------------------- main results
def t_main():
    """The headline table: 27 configurations, AUC-ROC, grouped by domain."""
    lines = ["\\begin{table}[htbp]", "\\centering", "\\small"]
    lines += caption(
        "Detection performance (AUC-ROC) for all 27 causal configurations. Rows are causal "
        "discovery algorithms, columns are regression variants, blocks are application "
        "domains. The best value within each domain is shown in bold.",
        "tab:main-results")
    lines += ["\\begin{tabular}{llrrr}", "\\toprule",
              "Domain & Algorithm & Linear / Ridge $\\uparrow$ & Polynomial $\\uparrow$ & RBF + Ridge $\\uparrow$" + NL,
              "\\midrule"]
    for di, (dom, dlabel) in enumerate(DOMAINS):
        allv = []
        for algo, _ in ALGOS:
            rows = {r["Model Variant"]: r for r in read(folder(algo, dom) + "/outputs/metrics_summary.csv")}
            allv += [float(rows[v]["AUC_ROC"]) for v in VARIANTS if v in rows]
        best = max(allv) if allv else None
        for ai, (algo, alabel) in enumerate(ALGOS):
            rows = {r["Model Variant"]: r for r in read(folder(algo, dom) + "/outputs/metrics_summary.csv")}
            cells = []
            for v in VARIANTS:
                if v not in rows:
                    cells.append("--")
                    continue
                x = float(rows[v]["AUC_ROC"])
                cells.append((BF + "%.4f" % x + "}") if x == best else "%.4f" % x)
            dcell = (MULTIROW + dlabel + "}") if ai == 0 else ""
            lines.append(dcell + " & " + alabel + " & " + " & ".join(cells) + NL)
        if di < len(DOMAINS) - 1:
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    write("tbl_main_results.tex", lines)


# ------------------------------------------------------------ per-domain detail
def t_domain_detail():
    """One full confusion-matrix table per domain: every metric, all nine configurations."""
    for dom, dlabel in DOMAINS:
        short = dlabel.split(" (")[0].lower()
        lines = ["\\begin{table}[htbp]", "\\centering", "\\footnotesize", "\\setlength{\\tabcolsep}{3pt}"]
        lines += caption(
            "Complete detection metrics for the " + short + " domain. The threshold is the "
            "95th percentile of the fault-free score distribution, computed without reference "
            "to any anomaly label.",
            "tab:detail-" + dom)
        lines += ["\\begin{tabular}{llrrrrrrrrrr}", "\\toprule",
                  "Algorithm & Variant & Thr. & TP $\\uparrow$ & FP $\\downarrow$ & TN $\\uparrow$ & FN $\\downarrow$ & Acc. $\\uparrow$ & Prec. $\\uparrow$ & Rec. $\\uparrow$ & F1 $\\uparrow$ & AUC $\\uparrow$" + NL,
                  "\\midrule"]
        # Bolding is computed over all nine rows at once and only then split back into
        # the per-algorithm blocks.
        block, acells = [], []
        for ai, (algo, alabel) in enumerate(ALGOS):
            rows = {r["Model Variant"]: r for r in read(folder(algo, dom) + "/outputs/metrics_summary.csv")}
            for vi, v in enumerate(VARIANTS):
                if v not in rows:
                    continue
                r = rows[v]
                acells.append(((MULTIROW + alabel + "}") if vi == 0 else "", ai))
                block.append([VSHORT[v], "%.3f" % float(r["Threshold"]), r["TP"], r["FP"],
                              r["TN"], r["FN"], r["Accuracy"], r["Precision"], r["Recall"],
                              r["F1"], r["AUC_ROC"]])
        # Only the rate columns are bolded, and the confusion counts deliberately are
        # not. The nine rows do not share a denominator: PCMCI subsamples at its own
        # rate, so on robotics it scores 181 observations where GES and CAM-UV score
        # 1378. Bolding the raw counts would hand PCMCI "fewest false positives" for
        # having scored seven times fewer samples, which is the exact confusion
        # Section~\\ref{sec:method-preprocessing} declares as this study's principal
        # threat to internal validity. A rate is comparable across denominators; a
        # count is not. Threshold is a setting rather than a score and is left alone.
        bold_best(block, [6, 7, 8, 9, 10])
        last_ai = None
        for (acell, ai), cells in zip(acells, block):
            if last_ai is not None and ai != last_ai:
                lines.append("\\midrule")
            lines.append(acell + " & " + " & ".join(str(c) for c in cells) + NL)
            last_ai = ai
        lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
        write("tbl_detail_" + dom + ".tex", lines)


# ---------------------------------------------------------------------- baselines
def dmatch(v, dom):
    """Match a Dataset cell against a domain key, across the labels used in the CSVs."""
    v = str(v).lower()
    return ((dom in v)
            or (dom == "robotic" and "pepper" in v)
            or (dom == "healthcare" and ("ecg" in v or "ptb" in v))
            or (dom == "industrial" and "tep" in v))


def best_causal(dom):
    """Highest AUC-ROC over the nine causal configurations in a domain."""
    vals = []
    for algo, _ in ALGOS:
        for r in read(folder(algo, dom) + "/outputs/metrics_summary.csv"):
            vals.append(float(r["AUC_ROC"]))
    return max(vals) if vals else None


def t_baselines():
    """Neural and parameter-free baselines against the best causal configuration.

    The neural rows are means over three seeds; the standard deviation is carried into the
    table because a difference smaller than it is not a difference. The architecture is in
    the Variant column -- Model is constant at "Neural Baseline" -- so the row label is
    taken from Variant.
    """
    # The tuned file is preferred wherever it exists. Both sets of numbers are produced by
    # the same script; the difference is that the tuned run searches the twelve-configuration
    # grid on every domain, where the earlier run searched only robotics and gave healthcare
    # and industrial a single fixed configuration. Comparing a tuned causal pipeline against
    # an untuned neural one is the specific criticism this thesis makes of the literature,
    # so it must not appear in this thesis's own baseline table.
    neural = (read("Baselines/outputs/neural_all_domains_tuned.csv")
              or read("Baselines/outputs/neural_all_domains.csv"))
    trivial = read("Baselines/outputs/trivial_baseline.csv")
    if not neural:
        print("  (skipped baselines: no neural_all_domains CSV present)")
        return

    archs = []
    for r in neural:
        if r["Variant"] not in archs:
            archs.append(r["Variant"])

    # Assemble the whole table as values first, so the column maximum can be marked
    # honestly. Bolding the best causal row regardless of the column would hide the
    # industrial result, which is the one the discussion has to confront.
    body = []
    for a in archs:
        vals = []
        for dom, _ in DOMAINS:
            m = [r for r in neural if r["Variant"] == a and dmatch(r["Dataset"], dom)]
            vals.append((float(m[0]["AUC_ROC"]), float(m[0]["AUC_std"])) if m else None)
        body.append((esc(a.replace(" Autoencoder", "")) + " autoencoder", vals, False))
    if trivial:
        vals = []
        for dom, _ in DOMAINS:
            m = [r for r in trivial if dmatch(r["Dataset"], dom)]
            vals.append((float(m[0]["AUC_ROC"]), None) if m else None)
        body.append(("Trivial control, mean $|z|$", vals, True))
    vals = []
    for dom, _ in DOMAINS:
        b = best_causal(dom)
        vals.append((b, None) if b is not None else None)
    body.append(("Best causal configuration", vals, True))

    col_max = []
    for i in range(len(DOMAINS)):
        seen = [v[i][0] for _, v, _ in body if v[i] is not None]
        col_max.append(max(seen) if seen else None)

    lines = ["\\begin{table}[htbp]", "\\centering", "\\small"]
    lines += caption(
        "Non-causal reference points, as AUC-ROC. The neural autoencoders read the same "
        "variables and apply the same 95th-percentile fault-free threshold as the causal "
        "pipelines, and are reported as the mean over three seeds with the standard "
        "deviation across them. They run at PCMCI's scoring resolution in every domain, "
        "which matches the best causal configuration on robotics and industrial but not "
        "on healthcare. Table~\\ref{tab:baseline_parity} sets out what each side "
        "was given in each domain, including the direction of that asymmetry, which runs "
        "against this thesis instead of for it. The trivial control is a parameter-free "
        "mean absolute $z$-score with no learned parameters at all. Bold marks the best "
        "value in each column, whichever family it belongs to.",
        "tab:baselines")
    lines += ["\\begin{tabular}{lccc}", "\\toprule",
              "Method & Robotics $\\uparrow$ & Healthcare $\\uparrow$ & Industrial $\\uparrow$" + NL, "\\midrule"]
    for bi, (label, vals, rule) in enumerate(body):
        if rule:
            lines.append("\\midrule")
        cells = []
        for i, v in enumerate(vals):
            if v is None:
                cells.append("--")
                continue
            mu, sd = v
            txt = "%.4f" % mu if sd is None else "%.4f \\pm %.4f" % (mu, sd)
            cells.append(("$" + BFM + txt + "}$") if mu == col_max[i] else "$" + txt + "$")
        lines.append(label + " & " + " & ".join(cells) + NL)
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    write("tbl_baselines.tex", lines)


# -------------------------------------------------------------------- bootstrap
def t_bootstrap():
    rows = read("tools/bootstrap_intervals.csv")
    if not rows:
        print("  (skipped bootstrap: CSV absent)")
        return
    # Ten columns, three of them long strings, ran past the text block and dropped the
    # last four off the page. Dataset is redundant -- Folder already names the domain --
    # and the variant abbreviates, which brings the table inside the margin.
    # The Folder column printed the results directory verbatim -- CAM\_UV\_healthcare --
    # which is a path, not a label, and set an underscore in every one of 27 rows. The
    # folder encodes exactly two facts, so it is split into the two columns it stands for.
    FOLDER_ALGO = {"PCMCI": "PCMCI", "GES": "GES", "CAM_UV": "CAM-UV"}
    FOLDER_DOM = {"robotic": "Robotics", "robotics": "Robotics",
                  "healthcare": "Healthcare", "industrial": "Industrial"}

    def split_folder(v):
        for pre, algo in FOLDER_ALGO.items():
            if v.startswith(pre + "_"):
                return algo, FOLDER_DOM.get(v[len(pre) + 1:], v[len(pre) + 1:])
        return v, ""

    HEAD = [("Folder", "Folder"), ("Variant", "Variant"), ("AUC", "AUC $\\uparrow$"),
            ("CI_low", "CI low"), ("CI_high", "CI high"), ("n", "$n$"),
            ("block", "$L$"), ("HM_low", "HM low"), ("HM_high", "HM high")]
    present = [(key, head) for key, head in HEAD if key in rows[0]]
    print("  [bootstrap columns: " + str([h for _k, h in present]) + "]")
    align = "lll" + "r" * (len(present) - 2)
    lines = ["\\begin{table}[htbp]", "\\centering", "\\footnotesize", "\\setlength{\\tabcolsep}{3pt}"]
    lines += caption(
        "Moving-block bootstrap confidence intervals on AUC-ROC, with the analytical "
        "Hanley--McNeil (HM) interval alongside for comparison, which is what the HM low "
        "and HM high columns report. Blocks preserve the serial "
        "correlation of the score series, which an i.i.d.\\ resample would destroy and which "
        "would otherwise make every interval spuriously narrow. $L$ is the block length, "
        "derived per series as $\\max(2, \\operatorname{round}(n^{1/3}))$. The bold AUC "
        "in each algorithm-domain block is the best of the three regression variants on "
        "that data; no comparison is drawn between blocks, which score different "
        "observations.",
        "tab:bootstrap")
    heads = []
    for _k, head in present:
        heads += ["Algorithm", "Domain"] if head == "Folder" else [head]
    lines += ["\\begin{tabular}{" + align + "}", "\\toprule",
              " & ".join(heads) + NL, "\\midrule"]
    body, auc_col = [], None
    for r in rows:
        cells = []
        for key, _head in present:
            v = r.get(key, "")
            if key == "Folder":
                cells += list(split_folder(v))
            elif key == "Variant":
                cells.append(esc(VSHORT.get(v, v)))
            else:
                if key == "AUC":
                    auc_col = len(cells)
                cells.append(esc(v))
        body.append(cells)
    # Bolding runs within one algorithm-domain block and never across them. The best
    # of three regression variants on the same data is a comparison this table can
    # support; the best of 27 rows drawn from three different datasets is not.
    if auc_col is not None:
        i = 0
        while i < len(body):
            j = i
            while j < len(body) and body[j][:2] == body[i][:2]:
                j += 1
            bold_best(body[i:j], [auc_col])
            i = j
    for cells in body:
        lines.append(" & ".join(cells) + NL)
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    write("tbl_bootstrap.tex", lines)


