def _sign_cell(r):
    """How the classes split: favouring SHAP, favouring the causal side, tied.

    An earlier version printed only the first over the class count, so a 2--0--1
    split read as 2--1 and a unanimous panel looked divided. Ties carry no
    evidence either way and the sign test discards them, so they are shown
    rather than folded into the losing side.
    """
    return "%s/%s/%s" % (r["n_pos"], r["n_neg"], r["n_tie"])


def _verdict(r):
    return {"yes": "yes", "no": "no"}.get(r["separates"], "---")


