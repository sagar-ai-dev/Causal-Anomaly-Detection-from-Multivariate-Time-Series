def t_validation():
    rows = read("tools/algorithm_validation.csv")
    if not rows:
        print("  (skipped validation: CSV absent)")
        return
    pretty = {
        "rls_vs_ols_max_abs_diff": ("RLS at $\\lambda=1$ equals ordinary least squares",
                                    "max $|w_{\\mathrm{RLS}} - w_{\\mathrm{OLS}}|$"),
        "rls_forgetting_estimate": ("RLS with forgetting, $\\lambda = 0.995$",
                                    "estimate of a coefficient stepping to $2.5$"),
        "rls_no_forgetting_estimate": ("RLS without forgetting, $\\lambda = 1$",
                                       "same coefficient, no forgetting"),
        "drift_broken_relationship": ("Drift when the relationship breaks",
                                      "mean drift after the change"),
        "drift_rescaled_intact": ("Drift when values are rescaled but the relationship holds",
                                  "mean drift after the change"),
        "drift_unchanged": ("Drift when nothing changes", "mean drift, second half"),
    }
    # Two prose columns and a number. With plain `l` columns the prose sets its natural
    # width, the table exceeds the text block, and the Value column is pushed off the
    # page -- which is how this table shipped with its results invisible. X columns
    # divide the remaining width between the two prose columns instead.
    lines = ["\\begin{table}[htbp]", "\\centering", "\\small"]
    lines += caption(
        "Numerical validation of the detector against closed-form answers. Each row "
        "constructs a problem whose result is known independently of the implementation and "
        "confirms that the implementation reaches it.",
        "tab:validation")
    lines += ["\\begin{tabularx}{\\textwidth}{@{}Xl r@{}}", "\\toprule",
              "Check & Quantity & Value" + NL, "\\midrule"]
    for r in rows:
        q = r.get("quantity", "")
        v = str(r.get("value", ""))
        name, desc = pretty.get(q, (esc(q), ""))
        lines.append(name + " & " + desc + " & " + sci(v) + NL)
    lines += ["\\bottomrule", "\\end{tabularx}", "\\end{table}"]
    write("tbl_validation.tex", lines)


